import { useMemo } from 'react'
import type { DesignSettings, EditorDraftSettings, ProjectSettings } from '../model/types'

export function useEditorDraftSnapshot({
  projectSettings,
  designSettings,
}: {
  projectSettings: ProjectSettings
  designSettings: DesignSettings
}) {
  const {
    activeTool,
    projectName,
    zoom,
    videoAudio,
    exportFormat,
    exportScale,
    exportWatermark,
  } = projectSettings
  const {
    selectedFilter,
    filterIntensity,
    backgroundRemoved,
    backgroundColor,
    drawingColor,
    brushSize,
    activeDrawingMode,
    brightness,
    contrast,
    saturation,
    textValue,
    fontFamily,
    fontSize,
    textColor,
    textBackground,
    textOpacity,
    textOutline,
    textOutlineWidth,
    textShadow,
    shapeKind,
    fillColor,
    transparentFill,
    strokeColor,
    strokeWidth,
    shapeOpacity,
  } = designSettings

  return useMemo<EditorDraftSettings>(() => ({
    projectName,
    activeTool,
    zoom,
    selectedFilter,
    filterIntensity,
    backgroundRemoved,
    backgroundColor,
    drawingColor,
    brushSize,
    activeDrawingMode,
    brightness,
    contrast,
    saturation,
    videoAudio: {
      ...videoAudio,
      music: { ...videoAudio.music, url: '' },
      voice: { ...videoAudio.voice, url: '' },
    },
    textValue,
    fontFamily,
    fontSize,
    textColor,
    textBackground,
    textOpacity,
    textOutline,
    textOutlineWidth,
    textShadow,
    shapeKind,
    fillColor,
    transparentFill,
    strokeColor,
    strokeWidth,
    shapeOpacity,
    exportFormat,
    exportScale,
    exportWatermark,
  }), [
    activeDrawingMode,
    activeTool,
    backgroundColor,
    backgroundRemoved,
    brightness,
    brushSize,
    contrast,
    drawingColor,
    exportFormat,
    exportScale,
    exportWatermark,
    fillColor,
    filterIntensity,
    fontFamily,
    fontSize,
    projectName,
    saturation,
    selectedFilter,
    shapeKind,
    shapeOpacity,
    strokeColor,
    strokeWidth,
    textBackground,
    textColor,
    textOpacity,
    textOutline,
    textOutlineWidth,
    textShadow,
    textValue,
    transparentFill,
    videoAudio,
    zoom,
  ])
}